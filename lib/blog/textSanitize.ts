// Stage1/Stage2にMarkdownを使わないよう繰り返し指示しても、モデルは
// 見出しの#や強調の**を一定確率で出力してしまう。
// プロンプト任せにせず、保存直前に機械的に除去する最終防波堤として用意する。
//
// ・や1.のような箇条書き記号は対象外とする。これらはStyle Profileで学習した
// 「そのサロンが実際に使っている記号」として意図的に許可している場合があり、
// 日本語の自然な文章でも普通に使われるため、Markdown由来の#や**とは扱いを分ける。
// (blog-appの lib/textSanitize.ts を無変更で移植)

export function stripMarkdownArtifacts(text: string): string {
  return text
    // 行頭の見出し記号（# ## ### ...）を除去し、テキストだけ残す。
    .replace(/^#{1,6}\s+/gm, "")
    // 太字/斜体のMarkdown記号を除去（囲まれたテキストは残す）。
    .replace(/\*\*([^*\n]+)\*\*/g, "$1")
    .replace(/__([^_\n]+)__/g, "$1")
    // コードブロック・インラインコードの記号を除去。
    .replace(/```[a-zA-Z]*\n?/g, "")
    .replace(/`([^`\n]+)`/g, "$1")
    // Markdownの水平線（---, ***, ___ のみの行）を除去。
    .replace(/^[-*_]{3,}\s*$/gm, "")
    // 除去した結果できた余分な空行を整理する。
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
